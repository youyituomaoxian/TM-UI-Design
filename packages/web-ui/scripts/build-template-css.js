#!/usr/bin/env node
/*
 * build-template-css.js — 单一真源构建：globals + components + framework + utilities → 弘讯web端design-system/template.css
 *
 * 目标（第一性原理）：视觉真理从 N=3 压到 N=1。
 *   template.css 不再是「第三份手写实现」（历史上与 globals/components 各自漂移，导致
 *   「生成页与组件对不上」），而是四份唯一手写真源的合并产物 → HTML 生成页与 React 组件
 *   共用同一套样式，天然视觉一致。
 *
 * 合并顺序（变量先定义，工具类置后便于覆盖）：
 *   globals.css(变量/暗色/密度) → components.css(组件) → framework.css(框架外壳) → utilities.css(工具/KPI)
 *
 * 用法：
 *   node scripts/build-template-css.js
 *   npm run build:template
 */
const fs = require('fs');
const path = require('path');

const PKG = path.resolve(__dirname, '..');
const STYLES = path.join(PKG, 'src', 'styles');
const OUT = path.resolve(PKG, '..', '..', '弘讯web端design-system', 'template.css');

const SRC = [
  ['globals.css', '变量层（AUTO-GENERATED，改 tokens.json 后跑 map-tokens.js 重生成）'],
  ['components.css', '组件层（33 件 shadcn 风格组件 + 基础组件，含 .btn flex 修复）'],
  ['framework.css', '框架层（B 端后台固定框架外壳，唯一框架真源；G8 固定滚动 / G9 折叠 / 品牌表面树选中 / 暗色 chrome）'],
  ['utilities.css', '工具/KPI 层（布局工具 + KPI 图标 currentColor 原语 + 图表色便捷类）'],
];

function stripComments(css) {
  // 各源文件头部说明性注释在合并后由统一 AUTO-GENERATED 头替代，此处全去。
  return css.replace(/\/\*[\s\S]*?\*\//g, '');
}

function main() {
  const parts = [];
  const provenance = [];
  for (const [file, desc] of SRC) {
    const fp = path.join(STYLES, file);
    if (!fs.existsSync(fp)) {
      console.error('❌ 缺少源文件: ' + fp);
      process.exit(1);
    }
    const raw = fs.readFileSync(fp, 'utf8');
    provenance.push(' *   - ' + file + '  ' + desc);
    parts.push(stripComments(raw).trim());
  }

  const header = [
    '/*',
    ' * template.css — AUTO-GENERATED by packages/web-ui/scripts/build-template-css.js. DO NOT EDIT.',
    ' * 真源（手写，四件，按序合并）：packages/web-ui/src/styles/{globals,components,framework,utilities}.css',
    ' * 视觉真理 N=1：本文件不再是第三份手写实现，而是上方四份唯一真源的合并产物，',
    ' *   故 HTML 生成页与 React 组件共用同一套样式，天然视觉一致（根治「生成页与组件对不上」漂移）。',
    ' * 改样式请改上方对应真源文件后重跑本脚本（npm run build:template）。',
    ' * 来源明细：',
    ...provenance,
    ' */',
    '',
  ].join('\n');

  const out = header + parts.join('\n\n') + '\n';
  fs.writeFileSync(OUT, out, 'utf8');

  const bytes = Buffer.byteLength(out);
  console.log('✅ 已生成 ' + path.relative(PKG, OUT));
  console.log('   真源: ' + SRC.map(s => s[0]).join(' + '));
  console.log('   体积: ' + (bytes / 1024).toFixed(1) + ' KB');
}

main();
